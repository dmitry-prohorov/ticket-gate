#!/usr/bin/env node
// CLI shim for the db-schema pack (tools/checks/supabase-next/db-schema.mjs): binds this repo's values.
//
//   pnpm db:schema                      dump the local stack and rewrite supabase/schema/
//   node tools/db-schema.mjs --dump=PATH --cron=PATH --out=DIR
//                                       read inputs from files (tests, no stack)
//
// Exit: 0 written, 1 error (nothing written or deleted), 2 unknown flag.

import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import {
  dbSchema,
  normalise as packNormalise,
  parseToc,
  readCronFromStack as packReadCron,
  readDumpFromStack as packReadDump,
  splitDump as packSplitDump,
  writeSnapshot,
} from '../../../checks/db-schema.mjs';

const ROOT = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  '..',
  '..',
  '..',
  '..',
);

export const OUT_REL = 'supabase/schema';
export const GENERATED_HEADER =
  '-- Generated by pnpm db:schema (tools/db-schema.mjs) from the local database. Never hand-edit; never applied. Rationale lives in supabase/migrations/.';

const TOOL = 'tools/db-schema.mjs';
const START = 'pnpm supabase start';
const RESET = 'pnpm db:reset';

const schema = dbSchema({
  root: ROOT,
  out: OUT_REL,
  header: GENERATED_HEADER,
  tool: TOOL,
  name: 'db:schema',
  usage: `usage: node ${TOOL} [--dump=PATH] [--cron=PATH] [--out=DIR]`,
  start: START,
  reset: RESET,
});

export { parseToc, writeSnapshot };
export const normalise = (dump) => packNormalise(dump, TOOL);
export const renderCron = schema.renderCron;
export const buildSnapshot = schema.buildSnapshot;
export const splitDump = (dump) =>
  packSplitDump(dump, { header: GENERATED_HEADER, tool: TOOL, reset: RESET });
export const readDumpFromStack = () => packReadDump(ROOT, START, RESET);
export const readCronFromStack = () => packReadCron(ROOT, START, RESET);

export function main(argv = process.argv.slice(2)) {
  const r = schema.run(argv);
  for (const l of r.out) console.log(l);
  for (const l of r.err) console.error(l);
  return r.code;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  process.exitCode = main();
}
