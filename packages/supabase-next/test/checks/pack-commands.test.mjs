// SNC-*: the commands the pack adds through packCommands. Scratch projects import the pack and the
// engine config by file URL and run the real bin, so the exit status is the one a script sees.
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import {
  mkdtempSync,
  readFileSync,
  readdirSync,
  realpathSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { after, test } from 'node:test';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { defineGate } from '../../../engine/config.mjs';
import { ENGINE_COMMANDS } from '../../../engine/commands-config.mjs';
import { dbSchema } from '../../checks/db-schema.mjs';
import { DB_SCHEMA_DEFAULTS, packCommandsFor } from '../../commands.mjs';
import { supabaseNext } from '../../index.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const PACK = join(HERE, '..', '..');
const BIN = join(PACK, '..', 'engine', 'bin', 'ticket-gate.mjs');
const CONFIG_URL = pathToFileURL(join(PACK, '..', 'engine', 'config.mjs')).href;
const PACK_URL = pathToFileURL(join(PACK, 'index.mjs')).href;
const FIXTURES = join(HERE, 'fixtures', 'db-schema');
const HEADER = '-- Generated by the demo project. Never hand-edit.';
const PREFLIGHT = {
  webEnv: { file: 'web/.env.local', missing: 'copy web/.env.example to web/.env.local' },
  anonKey: { file: 'functions/.env', name: 'ANON_KEY' },
};
const dirs = [];
after(() => dirs.forEach((d) => rmSync(d, { recursive: true, force: true })));

function scratch(config) {
  const dir = realpathSync(mkdtempSync(join(tmpdir(), 'gate-snc-')));
  dirs.push(dir);
  writeFileSync(join(dir, 'gate.config.mjs'), config);
  return dir;
}
const run = (cwd, ...args) => spawnSync(process.execPath, [BIN, ...args], { cwd, encoding: 'utf8' });
const files = (dir) => readdirSync(dir, { recursive: true }).filter((f) => f.endsWith('.sql')).sort();

test('SNC-1 supabaseNext with both options gives stack-preflight and db-schema, neither is an engine command, and defineGate accepts the pack; with neither, packCommands is {}', () => {
  const pack = supabaseNext({ stackPreflight: PREFLIGHT, dbSchema: { header: HEADER } });
  assert.deepEqual(Object.keys(pack.packCommands).sort(), ['db-schema', 'stack-preflight']);
  for (const name of Object.keys(pack.packCommands)) assert.ok(!ENGINE_COMMANDS.includes(name), name);
  assert.deepEqual(Object.keys(defineGate({ steps: [], packs: [pack] }).packCommands).sort(), [
    'db-schema',
    'stack-preflight',
  ]);
  assert.deepEqual(supabaseNext().packCommands, {});
  assert.deepEqual(Object.keys(supabaseNext({ dbSchema: { header: HEADER } }).packCommands), ['db-schema']);
  assert.deepEqual(Object.keys(supabaseNext({ stackPreflight: PREFLIGHT }).packCommands), ['stack-preflight']);
});

test('SNC-2 ticket-gate db-schema --dump --cron --out writes exactly dbSchema(opts).buildSnapshot(dump, cron); --bogus exits 2 with the usage on stderr', () => {
  const dir = scratch(`import { defineGate } from ${JSON.stringify(CONFIG_URL)};
import { supabaseNext } from ${JSON.stringify(PACK_URL)};
export default defineGate({ steps: [], packs: [supabaseNext({ dbSchema: { header: ${JSON.stringify(HEADER)} } })] });
`);
  const out = join(dir, 'snap');
  const dump = join(FIXTURES, 'dump.sql');
  const cron = join(FIXTURES, 'cron.json');
  const r = run(dir, 'db-schema', `--dump=${dump}`, `--cron=${cron}`, `--out=${out}`);
  assert.equal(r.status, 0, r.stderr);
  assert.match(r.stdout, /^db-schema: \d+ files written, 0 deleted in [0-9.]+s\n$/);
  const expected = dbSchema({ ...DB_SCHEMA_DEFAULTS, header: HEADER, root: dir }).buildSnapshot(
    readFileSync(dump, 'utf8'),
    JSON.parse(readFileSync(cron, 'utf8')),
  );
  assert.deepEqual(files(out), [...expected.keys()].sort());
  for (const [rel, text] of expected) assert.equal(readFileSync(join(out, rel), 'utf8'), text, rel);
  const bad = run(dir, 'db-schema', '--bogus');
  assert.equal(bad.status, 2);
  assert.equal(bad.stderr, `${DB_SCHEMA_DEFAULTS.usage}\n`);
});

test("SNC-3 ticket-gate stack-preflight --steps=bogus exits 2 naming the gate's services (unknown step id bogus: use db, e2e) and the default usage", () => {
  const step = (id) =>
    `{ id: ${JSON.stringify(id)}, when: true, cmd: 'run ${id}', why: 'why', notRun: 'not run', summary: () => 'ok', limitS: 10, reuse: { deny: [] }, stack: 'supabase' }`;
  const dir = scratch(`import { defineGate } from ${JSON.stringify(CONFIG_URL)};
import { supabaseNext } from ${JSON.stringify(PACK_URL)};
export default defineGate({
  steps: [${step('db')}, ${step('e2e')}],
  stacks: { supabase: { health: { step: 'db', preflight: () => 'a', ready: () => 'b' }, services: { db: ['db'], e2e: ['db', 'kong'] } } },
  stopOnRedBefore: 'db',
  dataPaths: {},
  packs: [supabaseNext({ stackPreflight: ${JSON.stringify(PREFLIGHT)} })],
});
`);
  const r = run(dir, 'stack-preflight', '--steps=bogus');
  assert.equal(r.status, 2, r.stderr);
  assert.equal(
    r.stderr,
    'unknown step id bogus: use db, e2e\nusage: ticket-gate stack-preflight --steps=<db,e2e> [--wait=<sec>]\n',
  );
});

test('SNC-4 dbSchema without header and stackPreflight without webEnv or anonKey throw TypeError at factory time', () => {
  assert.throws(() => supabaseNext({ dbSchema: {} }), TypeError);
  assert.throws(() => supabaseNext({ dbSchema: { header: '' } }), /dbSchema needs header/);
  assert.throws(() => supabaseNext({ stackPreflight: {} }), TypeError);
  assert.throws(
    () => supabaseNext({ stackPreflight: { webEnv: PREFLIGHT.webEnv } }),
    /stackPreflight needs webEnv/,
  );
  assert.throws(
    () => supabaseNext({ stackPreflight: { anonKey: PREFLIGHT.anonKey } }),
    /stackPreflight needs webEnv/,
  );
  assert.throws(
    () => supabaseNext({ stackPreflight: { ...PREFLIGHT, anonKey: { file: 'f', name: '' } } }),
    TypeError,
  );
});

test('SNC-5 db-schema defaults: out, tool, name, usage, start, reset are DB_SCHEMA_DEFAULTS and a given option overrides one', () => {
  assert.deepEqual(DB_SCHEMA_DEFAULTS, {
    out: 'supabase/schema',
    tool: 'ticket-gate db-schema',
    name: 'db-schema',
    usage: 'usage: ticket-gate db-schema [--dump=PATH] [--cron=PATH] [--out=DIR]',
    start: 'supabase start',
    reset: 'supabase db reset',
  });
  assert.ok(Object.isFrozen(DB_SCHEMA_DEFAULTS));
  const dir = scratch('export default {};\n');
  const rows = [];
  const log = console.error;
  console.error = (l) => rows.push(l);
  return packCommandsFor({ dbSchema: { header: HEADER, name: 'schema', usage: 'u: x' } })
    ['db-schema'](['--bogus'], { root: dir })
    .then((code) => {
      console.error = log;
      assert.equal(code, 2);
      assert.deepEqual(rows, ['u: x']);
    })
    .finally(() => {
      console.error = log;
    });
});
